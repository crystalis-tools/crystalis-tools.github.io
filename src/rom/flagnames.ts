const NAME_BY_ID = new Map<number, string>(FLAG_NAMES);

/** Every flag id with an explicit name, sorted low to high. */
export function namedFlagIds(): number[] {
  return [...NAME_BY_ID.keys()].sort((a, b) => a - b);
}

/**
 * Display name for a flag id. Named ids use their game-specific name;
 * everything else gets a generic name from its id range - $100-$17f are
 * "check" flags (one per key item/chest), $180-$1ff are scratch item-get
 * slots, $200-$27f are "has item" flags for the 0x49 item ids.
 */
export function flagLabel(id: number): string {
  const name = NAME_BY_ID.get(id);
  if (name) return name;
  if (id >= 0x100 && id < 0x180) return `Check 0x${hex(id & 0xff)}`;
  if (id >= 0x180 && id < 0x200) return `Buffer 0x${hex(id, 3)}`;
  if (id >= 0x200 && id < 0x280) return `Item 0x${hex(id, 3)}`;
  return `Flag 0x${hex(id, 3)}`;
}
